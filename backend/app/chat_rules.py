NO_KNOWLEDGE = "관련 지식 없음 — 이 질문과 관련된 안내가 없어요. 규칙 2~6대로 답하고 used_ids는 빈 배열."


def knowledge_block(items: list[dict] | None) -> str:
    """[참고 지식] — 항목마다 id · 카테고리 · 질문 · 답변. 비어 있으면 '관련 지식 없음'."""
    if not items:
        return NO_KNOWLEDGE
    return "\n\n".join(f"[{x['id']}] ({x['category']}) 질문: {x['question']}\n답변: {x['answer']}" for x in items)


def system_prompt(items: list[dict] | None) -> str:
    return f"{RULES}\n\n[참고 지식]\n{knowledge_block(items)}"
